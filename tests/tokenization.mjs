import assert from "node:assert/strict";
import { build } from "esbuild";
const compiled = await build({ stdin: { contents: "export * from './lib/shop/tokenize-card';", resolveDir: process.cwd() }, bundle: true, write: false, platform: "node", format: "esm" });
const { tokenizeCard } = await import("data:text/javascript;base64," + Buffer.from(compiled.outputFiles[0].text).toString("base64"));
const fields = { number: { value: "4000 0000 0000 0010" }, holder_name: { value: "CLIENTE EXEMPLO" }, expiry: { value: "12/2099" }, cvv: { value: "123" } };
const form = { querySelector: selector => fields[selector.match(/"([a-z_]+)"/)[1]], querySelectorAll: () => Object.values(fields) };
let calls = 0;
globalThis.fetch = async (url, options) => {
  calls++;
  assert.equal(new URL(url).origin, "https://api.pagar.me");
  assert.equal(new URL(url).pathname, "/core/v5/tokens");
  assert.equal(new URL(url).searchParams.get("appId"), "pk_fixture");
  assert.deepEqual(Object.keys(options.headers), ["Content-Type"]);
  const payload = JSON.parse(options.body);
  assert.equal(payload.card.number, "4000000000000010");
  assert.equal(payload.card.cvv, "123");
  assert.equal(payload.card.exp_month, 12);
  assert.equal(payload.card.exp_year, 2099);
  return Response.json({ id: "token_fixture", card: { holder_name: "CLIENTE EXEMPLO" } });
};
assert.equal(await tokenizeCard(form, "pk_fixture"), "token_fixture");
assert.equal(calls, 1);
assert(Object.values(fields).every(field => field.value === ""), "Card fields must be cleared after tokenization");
await assert.rejects(() => tokenizeCard(form, "sk_fixture"), /temporariamente indisponível/);
assert.equal(calls, 1, "A secret key must never be sent to the browser token endpoint");
await assert.rejects(() => tokenizeCard(form, "pk_fixture"), /Confira/);
assert.equal(calls, 1, "Invalid fields cannot start a network request");
Object.assign(fields.number, { value: "4000000000000010" }); Object.assign(fields.holder_name, { value: "CLIENTE EXEMPLO" }); Object.assign(fields.expiry, { value: "12/2099" }); Object.assign(fields.cvv, { value: "123" });
globalThis.fetch = async () => Response.json({ message: "Do not echo provider/card data" }, { status: 422 });
await assert.rejects(() => tokenizeCard(form, "pk_fixture"), error => /não conseguiu validar/.test(error.message) && !error.message.includes("Do not echo"));
console.log("PASS: browser tokenization targets only Pagar.me, uses a public key without Authorization, clears card fields and never exposes provider errors or card data to the shop.");
